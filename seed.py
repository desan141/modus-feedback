def seed_database(db, Ticket, Comment, RoutingRule, now):
    # One atomic first-run seed. Call inside the caller's BEGIN IMMEDIATE transaction.
    if db.scalar(select(Ticket.id).limit(1)) is not None:
        return
    existing_categories = set(db.scalars(select(RoutingRule.category)))
    for row in SEED_TICKETS:
        if row["category"] not in existing_categories:
            db.add(RoutingRule(
                category=row["category"], primary_assignee=row["assignee_role"],
                fallback_assignee="Администратор системы", is_primary_available=True,
            ))
            existing_categories.add(row["category"])
    resolutions = {
        "A-004": "Запланирован пробный обучающий семинар.",
        "A-008": "Создана учебная инструкция по передаче сложных задач.",
        "A-017": "Сейчас нет подходящего помещения; вернуться к вопросу при перепланировке.",
        "A-018": "Положительный отзыв зафиксирован и передан организаторам обучения.",
    }
    overdue_codes = {"A-003", "A-009", "A-013"}
    for number, source in enumerate(SEED_TICKETS, start=1):
        row = source.copy()
        action = row.pop("demo_action")
        # 2–6 days old for new tickets, 9–15 days for already reviewed tickets.
        age_days = 1 + number % 5 if row["status"] == "Новое" else 8 + number % 7
        created = now - timedelta(days=age_days, hours=number % 6)
        first_response = None if row["status"] == "Новое" else created + timedelta(hours=2 + number % 18)
        if row["code"] in overdue_codes:
            deadline = now - timedelta(days=1 + number % 3, hours=2)
        elif row["status"] in ("Закрыто", "Реализовано"):
            deadline = now - timedelta(days=1)
        else:
            deadline = now + timedelta(days=2 + number % 6)
        ticket = Ticket(
            id=number, **row, fallback_assignee_role="Администратор системы",
            final_resolution=resolutions.get(row["code"]),
            attachment_name=f"{row['code']}_example.txt" if number in (3, 5, 13) else None,
            created_at=created, first_response_at=first_response, deadline_at=deadline,
        )
        db.add(ticket)
        db.flush()
        if first_response:
            db.add(Comment(
                ticket_id=ticket.id, author_role=ticket.assignee_role,
                text=resolutions.get(row["code"], "Демонстрационный следующий шаг: " + action),
                created_at=first_response,
            ))


